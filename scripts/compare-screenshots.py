#!/usr/bin/env python3
"""Pixel-exact comparison of a rendered snapshot against a checked-in reference.

The references are regenerated by scripts/gen-media.py and land through
media-regen.yml from main, not in the look-changing PR.

Exit codes: 0 = identical; non-zero otherwise (1 = images differ, diff overlay
written; 2 = usage / size mismatch; an unreadable image raises).

NOTE: compare in RGB, never RGBA — ImageChops.difference of two opaque RGBA
images has an all-zero alpha band, and Pillow >= 10's getbbox() defaults to
alpha_only=True, which would make ANY two same-size images compare equal.
"""

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from PIL import Image, ImageChops


def compare_images(ref_path, cand_path, diff_path):
    """Returns an exit code (see module docstring)."""
    ref_path = Path(ref_path)
    cand_path = Path(cand_path)
    diff_path = Path(diff_path)

    with Image.open(ref_path) as im:
        ref = im.convert("RGB")
    with Image.open(cand_path) as im:
        cand = im.convert("RGB")

    if ref.size != cand.size:
        print(
            f"ERROR: Image sizes differ. Reference: {ref.size}, Candidate: {cand.size}"
        )
        return 2

    diff = ImageChops.difference(ref, cand)
    if diff.getbbox() is None:
        print(f"SUCCESS: {cand_path.name} is pixel-identical to {ref_path.name}.")
        return 0

    # A pixel differs when any band does, so the bands' maximum is its mask.
    r, g, b = diff.split()
    differs = ImageChops.lighter(ImageChops.lighter(r, g), b).point(
        lambda v: 255 if v else 0
    )
    mismatched = differs.histogram()[255]

    # Dim the background so the red overlay pops.
    out = Image.eval(cand, lambda v: v // 2)
    out.paste((255, 0, 0), mask=differs)

    w, h = ref.size
    total_pixels = w * h
    percent = (mismatched / total_pixels) * 100.0
    print(f"MISMATCH: {mismatched} / {total_pixels} pixels differ ({percent:.4f}%)")

    diff_path.parent.mkdir(parents=True, exist_ok=True)
    out.save(diff_path)
    print(f"Difference highlight image saved to: {diff_path}")
    return 1


BLACK = (0, 0, 0)
WHITE = (255, 255, 255)


class SelfTest(unittest.TestCase):
    """The comparator can actually FAIL: two required gates ride on it, so an
    always-green one would report success for any render."""

    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.dir = Path(tmp.name)
        self.diff_out = self.dir / "diff.png"

    def write(self, name, mode, color, size=(8, 8)):
        p = self.dir / name
        Image.new(mode, size, color).save(p)
        return p

    def test_differing_rgba_images_fail(self):
        # THE anti-rot check: opaque RGBA differing only in colour. Without the
        # RGB conversion this returns 0 and the whole gate is decorative.
        a = self.write("rgba_a.png", "RGBA", BLACK + (255,))
        b = self.write("rgba_b.png", "RGBA", WHITE + (255,))
        self.assertEqual(compare_images(a, b, self.diff_out), 1)

    def test_identical_images_pass(self):
        a = self.write("rgb_a.png", "RGB", BLACK)
        self.assertEqual(compare_images(a, a, self.diff_out), 0)

    def test_a_size_mismatch_errors(self):
        a = self.write("rgb_a.png", "RGB", BLACK)
        bigger = self.write("bigger.png", "RGB", BLACK, size=(16, 16))
        self.assertEqual(compare_images(a, bigger, self.diff_out), 2)

    def test_a_single_differing_pixel_fails_and_is_marked_red(self):
        grey = (200, 100, 50)
        spotted = Image.new("RGB", (10, 10), grey)
        spotted.putpixel((0, 0), WHITE)
        spot = self.dir / "spot.png"
        spotted.save(spot)
        flat = self.write("flat.png", "RGB", grey, size=(10, 10))
        self.assertEqual(compare_images(flat, spot, self.diff_out), 1)
        with Image.open(self.diff_out) as overlay:
            self.assertEqual(overlay.getpixel((0, 0)), (255, 0, 0))
            self.assertEqual(overlay.getpixel((1, 1)), (100, 50, 25), "dimmed")

    def test_the_cli_maps_argv_to_exit_codes(self):
        # The consumers subprocess this module rather than importing it, so argv
        # handling and the exit-code mapping need their own exercise.
        a = str(self.write("rgb_a.png", "RGB", BLACK))
        b = str(self.write("rgb_b.png", "RGB", WHITE))
        out = str(self.diff_out)
        for args, want, why in (
            ([a, a, out], 0, "identical images"),
            ([a, b, out], 1, "differing images"),
            ([a], 2, "wrong arity"),
            ([a, a, out, "1.0"], 2, "a fourth argument"),
        ):
            with self.subTest(why):
                run = subprocess.run(
                    [sys.executable, str(Path(__file__).resolve()), *args],
                    capture_output=True,
                    check=False,
                )
                self.assertEqual(run.returncode, want)


if __name__ == "__main__":
    if "--selftest" in sys.argv[1:]:
        unittest.main(argv=sys.argv[:1])

    if len(sys.argv) != 4:
        print("Usage: compare-screenshots.py <reference> <candidate> <diff_out>")
        print("       compare-screenshots.py --selftest")
        sys.exit(2)

    sys.exit(compare_images(sys.argv[1], sys.argv[2], sys.argv[3]))
